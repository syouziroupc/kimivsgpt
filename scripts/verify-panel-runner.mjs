import assert from "node:assert/strict";
import {runPanel,classifyFailure} from "../src/panel-runner.ts";
import {aggregatePanel} from "../src/panel.ts";
const primary=[{model:"A",tier:"frontier"},...["B","C","D"].map(model=>({model,tier:"economy"}))];
const reserve=[{model:"E",tier:"frontier"},{model:"F",tier:"economy"}];
const audit={verdict:"proceed",risk:0,issues:[],verify:[],next_step:"none",confidence:1};
const never=()=>new Promise(()=>{});
const run=async(fn,hedgeMs=15,budgetMs=100)=>{const calls=[];const result=await runPanel({primary,reserve,budgetMs,hedgeMs,invoke:m=>{calls.push(m);return fn(m);}});return {result,calls,agg:aggregatePanel(result,["A","E"])};};
let t=await run(async()=>audit);
assert.equal(t.calls.length,4);assert.equal(t.agg.coverage.complete,true);
t=await run(m=>m==="A"||m==="B"?never():Promise.resolve(audit));
assert.equal(t.calls.length,6);assert.equal(t.agg.coverage.complete,true);assert.equal(t.result.filter(x=>x.status==="failed").length,2);
t=await run(m=>m==="A"||m==="E"?never():Promise.resolve(audit));
assert.equal(t.agg.coverage.complete,false);assert.notEqual(t.agg.verdict,"proceed");
t=await run(m=>m==="B"?Promise.reject(new Error("5028 deprecated")):Promise.resolve(audit));
assert.equal(t.agg.coverage.complete,true);assert.ok(t.calls.includes("F"));assert.equal(t.result.find(x=>x.model==="B").error,"model_unavailable");
t=await run(m=>m==="A"||m==="B"?never():Promise.resolve(m==="C"?{...audit,verdict:"revise",risk:3}:audit));
assert.equal(t.agg.verdict,"revise");assert.equal(t.agg.risk,3);
t=await run(()=>never());assert.equal(t.agg.coverage.valid,0);assert.equal(t.agg.verdict,"verify");
assert.equal(classifyFailure(new Error("auditor_invalid_schema")),"invalid_output");
assert.equal(classifyFailure(new Error("429 capacity")),"upstream_capacity_or_quota");
console.log("panel failure injection passed");
